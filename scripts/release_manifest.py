#!/usr/bin/env python3
"""Generate and verify Covio's release identity.

The source of truth is release/release-manifest.json. The script generates:

- Kotlin constants
- Swift constants
- an Xcode xcconfig

It also creates and verifies the artifact manifest generated at package time.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import re
import subprocess
import sys
from dataclasses import dataclass
from typing import Any


ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE_MANIFEST = pathlib.Path("release/release-manifest.json")
KOTLIN_OUT = pathlib.Path("kmpDomain/src/com/wyz/covio/core/GeneratedReleaseIdentity.kt")
SWIFT_OUT = pathlib.Path("macosApp/src/Design/GeneratedReleaseIdentity.swift")
XCCONFIG_OUT = pathlib.Path("macosApp/ReleaseIdentity.generated.xcconfig")
PBXPROJ = pathlib.Path("macosApp/Covio.xcodeproj/project.pbxproj")
INFO_PLIST = pathlib.Path("macosApp/src/Info.plist")
SIGNING_XCCONFIG = pathlib.Path("macosApp/Signing.xcconfig")
HELPER_CONTRACT = pathlib.Path("kmpDomain/src/com/wyz/covio/core/HelperContract.kt")

GENERATED_HEADER = "// This file is generated by scripts/release_manifest.py. Do not edit."
GENERATED_XCCONFIG_HEADER = "// This file is generated by scripts/release_manifest.py. Do not edit."
SEMVER = re.compile(r"^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$")
COMMIT = re.compile(r"^[0-9a-f]{40}$")
ALLOWED_CHANNELS = {"internal", "public"}
SOURCE_REQUIRED = (
    "schemaVersion",
    "productVersion",
    "buildNumber",
    "channel",
    "helperProtocolVersion",
)
ARTIFACT_REQUIRED = (
    "schemaVersion",
    "releaseId",
    "productVersion",
    "buildNumber",
    "gitCommit",
    "helperProtocolVersion",
    "helperSHA256",
    "channel",
)


class ManifestError(Exception):
    pass


@dataclass(frozen=True)
class ReleaseSpec:
    schema_version: int
    product_version: str
    build_number: int
    channel: str
    helper_protocol_version: int


def _path(root: pathlib.Path, relative: pathlib.Path) -> pathlib.Path:
    return root / relative


def validate_spec(raw: dict[str, Any]) -> ReleaseSpec:
    missing = [key for key in SOURCE_REQUIRED if key not in raw]
    if missing:
        raise ManifestError(f"source manifest is missing: {', '.join(missing)}")
    if raw["schemaVersion"] != 1:
        raise ManifestError("schemaVersion must be 1")
    version = raw["productVersion"]
    if not isinstance(version, str) or not SEMVER.fullmatch(version):
        raise ManifestError(f"productVersion is invalid: {version!r}")
    build = raw["buildNumber"]
    if not isinstance(build, int) or isinstance(build, bool) or build < 1:
        raise ManifestError("buildNumber must be a positive integer")
    channel = raw["channel"]
    if channel not in ALLOWED_CHANNELS:
        raise ManifestError(f"channel must be one of {sorted(ALLOWED_CHANNELS)}")
    protocol = raw["helperProtocolVersion"]
    if not isinstance(protocol, int) or isinstance(protocol, bool) or protocol < 1:
        raise ManifestError("helperProtocolVersion must be a positive integer")
    return ReleaseSpec(
        schema_version=1,
        product_version=version,
        build_number=build,
        channel=channel,
        helper_protocol_version=protocol,
    )


def load_spec(root: pathlib.Path = ROOT) -> ReleaseSpec:
    path = _path(root, SOURCE_MANIFEST)
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as error:
        raise ManifestError(f"missing source manifest: {path}") from error
    except json.JSONDecodeError as error:
        raise ManifestError(f"invalid source manifest JSON: {error}") from error
    if not isinstance(raw, dict):
        raise ManifestError("source manifest must be a JSON object")
    return validate_spec(raw)


def release_id(spec: ReleaseSpec, commit: str) -> str:
    if not COMMIT.fullmatch(commit):
        raise ManifestError("gitCommit must be a full 40-character lowercase SHA")
    return f"{spec.product_version}+{spec.build_number}+{commit}"


def render_kotlin(spec: ReleaseSpec) -> str:
    return "\n".join(
        [
            GENERATED_HEADER,
            "",
            "package com.wyz.covio.core",
            "",
            'const val APP_VERSION = "' + spec.product_version + '"',
            f"const val APP_BUILD_NUMBER = {spec.build_number}L",
            'const val APP_RELEASE_CHANNEL = "' + spec.channel + '"',
            "",
        ]
    )


def render_swift(spec: ReleaseSpec) -> str:
    return "\n".join(
        [
            GENERATED_HEADER,
            "",
            "import Foundation",
            "",
            "enum GeneratedReleaseIdentity {",
            f'    static let productVersion = "{spec.product_version}"',
            f"    static let buildNumber = {spec.build_number}",
            f'    static let channel = "{spec.channel}"',
            f"    static let helperProtocolVersion = {spec.helper_protocol_version}",
            "}",
            "",
        ]
    )


def render_xcconfig(spec: ReleaseSpec) -> str:
    return "\n".join(
        [
            GENERATED_XCCONFIG_HEADER,
            f"MARKETING_VERSION = {spec.product_version}",
            f"CURRENT_PROJECT_VERSION = {spec.build_number}",
            f"COVIO_RELEASE_CHANNEL = {spec.channel}",
            "COVIO_GIT_COMMIT = development",
            "COVIO_RELEASE_ID = $(MARKETING_VERSION)+$(CURRENT_PROJECT_VERSION)+development",
            f"COVIO_HELPER_PROTOCOL_VERSION = {spec.helper_protocol_version}",
            "",
        ]
    )


def expected_outputs(root: pathlib.Path = ROOT) -> dict[pathlib.Path, str]:
    spec = load_spec(root)
    return {
        _path(root, KOTLIN_OUT): render_kotlin(spec),
        _path(root, SWIFT_OUT): render_swift(spec),
        _path(root, XCCONFIG_OUT): render_xcconfig(spec),
    }


def _atomic_write(path: pathlib.Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(text, encoding="utf-8")
    temporary.replace(path)


def _protocol_from_contract(root: pathlib.Path) -> int | None:
    path = _path(root, HELPER_CONTRACT)
    match = re.search(r'^const val HELPER_PROTOCOL_VERSION = "(\d+)"$', path.read_text(encoding="utf-8"), re.M)
    return int(match.group(1)) if match else None


def project_errors(root: pathlib.Path = ROOT) -> list[str]:
    spec = load_spec(root)
    errors: list[str] = []
    pbx = _path(root, PBXPROJ).read_text(encoding="utf-8")
    if re.search(r"^\s*(?:MARKETING_VERSION|CURRENT_PROJECT_VERSION)\s*=", pbx, re.M):
        errors.append("Xcode target must not duplicate version settings; use ReleaseIdentity.generated.xcconfig")
    signing = _path(root, SIGNING_XCCONFIG).read_text(encoding="utf-8")
    include = '#include "ReleaseIdentity.generated.xcconfig"'
    if include not in signing:
        errors.append(f"Signing.xcconfig must include {include}")
    plist = _path(root, INFO_PLIST).read_text(encoding="utf-8")
    for key in (
        "CFBundleVersion",
        "CovioReleaseChannel",
        "CovioGitCommit",
        "CovioReleaseId",
        "CovioHelperProtocolVersion",
    ):
        if f"<key>{key}</key>" not in plist:
            errors.append(f"Info.plist is missing {key}")
    if "<string>$(CURRENT_PROJECT_VERSION)</string>" not in plist:
        errors.append("CFBundleVersion must use $(CURRENT_PROJECT_VERSION)")
    contract_protocol = _protocol_from_contract(root)
    if contract_protocol != spec.helper_protocol_version:
        errors.append(
            "helperProtocolVersion mismatch: "
            f"manifest={spec.helper_protocol_version} contract={contract_protocol}"
        )
    return errors


def drift_errors(root: pathlib.Path = ROOT) -> list[str]:
    errors: list[str] = []
    for path, expected in expected_outputs(root).items():
        if not path.exists():
            errors.append(f"missing generated file: {path.relative_to(root)}")
        elif path.read_text(encoding="utf-8") != expected:
            errors.append(f"generated file is stale: {path.relative_to(root)}")
    errors.extend(project_errors(root))
    return errors


def write_generated(root: pathlib.Path = ROOT) -> None:
    for path, text in expected_outputs(root).items():
        _atomic_write(path, text)
    errors = project_errors(root)
    if errors:
        raise ManifestError("\n".join(errors))


def bump_build(root: pathlib.Path = ROOT, version: str | None = None) -> ReleaseSpec:
    path = _path(root, SOURCE_MANIFEST)
    raw = json.loads(path.read_text(encoding="utf-8"))
    spec = validate_spec(raw)
    new_version = version or spec.product_version
    candidate = {
        **raw,
        "productVersion": new_version,
        "buildNumber": spec.build_number + 1,
    }
    next_spec = validate_spec(candidate)
    _atomic_write(path, json.dumps(candidate, indent=2, ensure_ascii=False) + "\n")
    write_generated(root)
    return next_spec


def sha256_file(path: pathlib.Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def artifact_manifest(
    spec: ReleaseSpec,
    commit: str,
    helper_path: pathlib.Path,
) -> dict[str, Any]:
    if not helper_path.is_file():
        raise ManifestError(f"helper path is not a file: {helper_path}")
    return {
        "schemaVersion": 1,
        "releaseId": release_id(spec, commit),
        "productVersion": spec.product_version,
        "buildNumber": spec.build_number,
        "gitCommit": commit,
        "helperProtocolVersion": spec.helper_protocol_version,
        "helperSHA256": sha256_file(helper_path),
        "channel": spec.channel,
    }


def _write_json(path: pathlib.Path, data: dict[str, Any]) -> None:
    _atomic_write(path, json.dumps(data, indent=2, sort_keys=False) + "\n")


def verify_artifact(
    manifest_path: pathlib.Path,
    helper_path: pathlib.Path,
    root: pathlib.Path = ROOT,
) -> dict[str, Any]:
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (FileNotFoundError, json.JSONDecodeError) as error:
        raise ManifestError(f"cannot read artifact manifest: {error}") from error
    if not isinstance(manifest, dict):
        raise ManifestError("artifact manifest must be a JSON object")
    missing = [key for key in ARTIFACT_REQUIRED if key not in manifest]
    if missing:
        raise ManifestError(f"artifact manifest is missing: {', '.join(missing)}")
    for key in ("releaseId", "productVersion", "gitCommit", "helperSHA256", "channel"):
        if not isinstance(manifest[key], str):
            raise ManifestError(f"artifact {key} must be a string")
    for key in ("schemaVersion", "buildNumber", "helperProtocolVersion"):
        if not isinstance(manifest[key], int) or isinstance(manifest[key], bool):
            raise ManifestError(f"artifact {key} must be an integer")
    if not re.fullmatch(r"[0-9a-f]{64}", manifest["helperSHA256"]):
        raise ManifestError("artifact helperSHA256 must be 64 lowercase hex characters")
    spec = load_spec(root)
    if manifest["schemaVersion"] != 1:
        raise ManifestError("artifact schemaVersion must be 1")
    if manifest["productVersion"] != spec.product_version:
        raise ManifestError("artifact productVersion differs from source manifest")
    if manifest["buildNumber"] != spec.build_number:
        raise ManifestError("artifact buildNumber differs from source manifest")
    if manifest["channel"] != spec.channel:
        raise ManifestError("artifact channel differs from source manifest")
    if manifest["helperProtocolVersion"] != spec.helper_protocol_version:
        raise ManifestError("artifact helperProtocolVersion differs from source manifest")
    expected_release_id = release_id(spec, manifest["gitCommit"])
    if manifest["releaseId"] != expected_release_id:
        raise ManifestError("artifact releaseId does not match its version, build and commit")
    actual_hash = sha256_file(helper_path)
    if manifest["helperSHA256"] != actual_hash:
        raise ManifestError("artifact helperSHA256 does not match the helper binary")
    return manifest


def git_commit(root: pathlib.Path = ROOT) -> str:
    return subprocess.check_output(
        ["git", "-C", str(root), "rev-parse", "HEAD"], text=True
    ).strip()


def ensure_clean(root: pathlib.Path = ROOT) -> None:
    status = subprocess.check_output(
        ["git", "-C", str(root), "status", "--porcelain", "--untracked-files=normal"],
        text=True,
    )
    if status.strip():
        raise ManifestError("working tree is not clean:\n" + status.rstrip())


def _print_errors(errors: list[str]) -> int:
    for error in errors:
        print(error, file=sys.stderr)
    return 1


def main(argv: list[str] | None = None, root: pathlib.Path = ROOT) -> int:
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="command", required=True)

    sub.add_parser("write")
    sub.add_parser("check")
    sub.add_parser("check-clean")

    value = sub.add_parser("value")
    value.add_argument("field", choices=("productVersion", "buildNumber", "channel", "helperProtocolVersion"))

    release = sub.add_parser("release-id")
    release.add_argument("--commit")

    generate = sub.add_parser("generate-artifact")
    generate.add_argument("--helper", required=True, type=pathlib.Path)
    generate.add_argument("--output", required=True, type=pathlib.Path)
    generate.add_argument("--commit")
    generate.add_argument("--allow-dirty", action="store_true")

    verify = sub.add_parser("verify-artifact")
    verify.add_argument("manifest", type=pathlib.Path)
    verify.add_argument("--helper", required=True, type=pathlib.Path)

    bump = sub.add_parser("bump")
    bump.add_argument("--version")

    args = parser.parse_args(argv)
    try:
        if args.command == "write":
            write_generated(root)
            print("release identity generated")
            return 0
        if args.command == "check":
            errors = drift_errors(root)
            if errors:
                return _print_errors(errors)
            print("release identity is current")
            return 0
        if args.command == "check-clean":
            ensure_clean(root)
            errors = drift_errors(root)
            if errors:
                return _print_errors(errors)
            print("release identity and working tree are clean")
            return 0
        if args.command == "value":
            spec = load_spec(root)
            values = {
                "productVersion": spec.product_version,
                "buildNumber": spec.build_number,
                "channel": spec.channel,
                "helperProtocolVersion": spec.helper_protocol_version,
            }
            print(values[args.field])
            return 0
        if args.command == "release-id":
            commit = args.commit or git_commit(root)
            print(release_id(load_spec(root), commit))
            return 0
        if args.command == "generate-artifact":
            if not args.allow_dirty:
                ensure_clean(root)
            errors = drift_errors(root)
            if errors:
                return _print_errors(errors)
            commit = args.commit or git_commit(root)
            manifest = artifact_manifest(load_spec(root), commit, args.helper)
            output = args.output if args.output.is_absolute() else root / args.output
            _write_json(output, manifest)
            verify_artifact(output, args.helper, root)
            print(output)
            return 0
        if args.command == "verify-artifact":
            verify_artifact(args.manifest, args.helper, root)
            print("artifact manifest is valid")
            return 0
        if args.command == "bump":
            spec = bump_build(root, args.version)
            print(f"productVersion={spec.product_version} buildNumber={spec.build_number}")
            return 0
    except ManifestError as error:
        print(str(error), file=sys.stderr)
        return 1
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
